library(dplyr)
library(tibble)
library(stringr)
library(purrr)

parse_cells <- function(row_string) {
  cells <- str_split(str_squish(row_string), " ")[[1]]
  tibble(estimate = as.numeric(str_replace(cells, "\\(.*$", "")),
         se = suppressWarnings(as.numeric(str_match(
           cells, "\\(([^)]*)\\)"
         )[, 2])))
}

build_regression_table <- function(table_name, panel, outcomes, rows) {
  imap_dfr(rows, function(row_string, term) {
    parse_cells(row_string) |>
      mutate(
        table = table_name,
        panel = panel,
        term = term,
        column = outcomes,
        .before = 1
      )
  })
}

