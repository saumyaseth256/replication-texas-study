transition_panel <- function(panel, rows) {
  imap_dfr(rows, function(values, previous) {
    tibble(
      table = "Table 2",
      panel = panel,
      term = previous,
      column = c("L", "A", "R", "E"),
      estimate = values,
      se = NA_real_
    )
  })
}

